def site_t(key: str, language: str = "en") -> str:
    """Returns the requested site translation with an English fallback."""
    values = SITE_TRANSLATIONS.get(key)
    if values is None:
        return key
    language_index = {"en": 0, "te": 1, "hi": 2}.get(language, 0)
    return values[language_index] or values[0]


def translate_guidance(condition: str, field: str, original: str, language: str) -> str:
    """Translates the fixed seeded project guidance; unknown rows remain source text."""
    condition_translations = _GUIDANCE_TRANSLATIONS.get(condition.strip().lower())
    values = condition_translations.get(field) if condition_translations else None
    if values is None or original != values[0]:
        return original
    language_index = {"en": 0, "te": 1, "hi": 2}.get(language, 0)
    return values[language_index]
